#!/usr/bin/env node
// scripts/check-ui.mjs · kit v0.3.0 · zero dependencies (uses the repo's TypeScript), Node 24
// Type-checks the inline <script>s of each plugin's ui.html against kit.d.ts with tsc's JSDoc
// checker, and reports errors at ui.html line numbers.
//
//   node scripts/check-ui.mjs [--keep] [dir ...]      (--keep leaves the temp folder for debugging)
//
// Default dirs: "." plus every examples/* folder that has a manifest.json. Exits 1 on any error,
// including a folder with nothing to check (a typo in a folder argument never passes).
// tsc cannot read <script> inside HTML, so each inline classic script is copied, in document order,
// to a temp .js file (separate classic scripts share one global scope in tsc just as in the browser).
// The kit runtime (<script data-kit="runtime">) must pass strict mode on its own. Host scripts are
// checked non-strict: untyped host code is fine, but typos and wrong kit calls still fail.
// type="module" scripts have their own scope and are skipped with a warning (the kit's are classic).
// ES2020 is enforced twice: the lib stops at es2020 (APIs), and a parse of each script flags newer
// syntax (??=, class fields, #private, ...), which tsc's target alone never rejects.

import { spawnSync } from 'node:child_process';
import {
  copyFileSync, existsSync, mkdtempSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { basename, dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const rel = (path) => relative(process.cwd(), path).split(sep).join('/') || '.';

// The runtime publishes window.kit; kit.d.ts types it but stays DOM-free (it also compiles in
// code.ts), so the Window augmentation lives here. Without a runtime there is no kit global, and
// a host call to kit.fit() fails the check as it would fail in the browser.
const GLOBALS = `// Generated by scripts/check-ui.mjs.
interface Window { kit: KitUiApi }
declare var kit: KitUiApi;
`;
const NO_GLOBALS = '// Generated by scripts/check-ui.mjs. No kit runtime in this ui file, so no window.kit.\n';

// ES2020 is the kit's browser baseline (Figma's desktop app and older browsers), so the lib stops
// there: Array.prototype.at, Object.hasOwn and other later APIs fail the check.
const jsconfig = (strict, files) => JSON.stringify({
  compilerOptions: {
    checkJs: true, allowJs: true, noEmit: true, target: 'es2020', lib: ['es2020', 'dom'], types: [],
    strict, skipLibCheck: true,
  },
  files: ['kit.d.ts', 'globals.d.ts', ...files],
}, null, 2);

// Prefer the pinned compiler in node_modules; fall back to a global tsc.
function tscCommand() {
  const local = join(REPO, 'node_modules', 'typescript', 'bin', 'tsc');
  return existsSync(local) ? [process.execPath, local] : ['tsc'];
}

// The same TypeScript as a library, for the syntax check; null when only a global tsc exists.
function typescript() {
  try {
    return createRequire(join(REPO, 'package.json'))('typescript');
  } catch {
    return null;
  }
}

function defaultDirs(root = '.') {
  const examples = join(root, 'examples');
  if (!existsSync(examples)) return [root];
  const found = readdirSync(examples).sort().map((name) => join(examples, name));
  return [root, ...found.filter((dir) => existsSync(join(dir, 'manifest.json')))];
}

// The ui file(s) the manifest names, or ui.html. A broken manifest is the audit's job to report
// (a leading byte-order mark is skipped here); a missing ui file or folder is an error here too.
function uiFiles(dir) {
  if (!existsSync(dir)) return { files: [], errors: [`${rel(dir)}  check-ui  no such folder`] };
  let ui;
  try {
    ui = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8').replace(/^\uFEFF/, ''))?.ui;
  } catch {
    ui = undefined;
  }
  const named = typeof ui === 'string' ? [ui]
    : ui && typeof ui === 'object' ? Object.values(ui).filter((v) => typeof v === 'string')
    : [];
  const paths = (named.length ? named : ['ui.html']).map((name) => join(dir, name));
  const why = named.length ? 'manifest.json names this ui file, but it does not exist'
    : 'no ui.html here, and manifest.json names no ui file; nothing to check';
  return { files: paths.filter(existsSync), errors: paths.filter((p) => !existsSync(p)).map((p) => `${rel(p)}  check-ui  ${why}`) };
}

// Line numbers as editors and the HTML parser count them: a new line after \r\n, \n or \r.
const htmlLine = (text, offset) => text.slice(0, offset).split(/\r\n|\r|\n/).length;
// tsc also breaks lines at U+2028 and U+2029, so its (line, column) is turned back into an offset.
function tscOffset(script, line, column) {
  script.lineStarts ??= [0, ...[...script.body.matchAll(/\r\n|[\n\r\u2028\u2029]/g)].map((m) => m.index + m[0].length)];
  return (script.lineStarts[line - 1] ?? script.body.length) + column - 1;
}

const ATTR = /([^\s"'<>/=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>`]+)))?/g;
// { name: value } for a tag's attribute text; the first of a repeated attribute wins, as in HTML.
function attributes(text) {
  const out = {};
  for (const m of text.matchAll(ATTR)) out[m[1].toLowerCase()] ??= m[2] ?? m[3] ?? m[4] ?? '';
  return out;
}
// The type values a browser runs as a classic script (HTML's JavaScript MIME type essences).
const CLASSIC_TYPE = /^(?:(?:text|application)\/(?:x-)?(?:java|ecma)script|text\/(?:javascript1\.[0-5]|jscript|livescript))$/;

// Inline scripts, with the ui.html offset and line where each body starts. Comments are matched
// first so a commented-out <script> is skipped; so are src, JSON and other data blocks. Module
// scripts come back with module: true, for checkDir to skip (they have their own scope).
export function inlineScripts(html) {
  const out = [];
  for (const m of html.matchAll(/<!--[\s\S]*?-->|<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    if (m[1] === undefined) continue;
    const attrs = attributes(m[1]);
    const type = (attrs.type ?? '').trim().toLowerCase();
    if ('src' in attrs || (type && type !== 'module' && !CLASSIC_TYPE.test(type))) continue;
    const start = m.index + m[0].indexOf('>') + 1;
    out.push({ body: m[2], start, line: htmlLine(html, start), runtime: attrs['data-kit'] === 'runtime', module: type === 'module' });
  }
  return out;
}

// Syntax newer than ES2020, as [{ offset, what }] (one per line). tsc's target limits nothing when
// it emits nothing, so this walks the parse tree; a transpile to ES2020 that differs from the
// ESNext one catches whatever the walk does not name, reported at the script's start.
export function newerSyntax(ts, body) {
  const K = ts.SyntaxKind;
  const LOGICAL = new Set([K.QuestionQuestionEqualsToken, K.BarBarEqualsToken, K.AmpersandAmpersandEqualsToken]);
  const file = ts.createSourceFile('script.js', body, ts.ScriptTarget.ESNext, true, ts.ScriptKind.JS);
  const found = [];
  const add = (node, what) => {
    const offset = node.getStart(file);
    const line = file.getLineAndCharacterOfPosition(offset).line;
    if (!found.some((f) => f.line === line)) found.push({ offset, line, what });
  };
  (function visit(node) {
    if (ts.isBinaryExpression(node) && LOGICAL.has(node.operatorToken.kind)) add(node.operatorToken, `${node.operatorToken.getText(file)} (ES2021)`);
    else if ((ts.isNumericLiteral(node) || ts.isBigIntLiteral(node)) && node.getText(file).includes('_')) add(node, 'a numeric separator (ES2021)');
    else if (ts.isPrivateIdentifier(node)) add(node, `the private name ${node.text} (ES2022)`);
    else if (ts.isPropertyDeclaration(node)) add(node, 'a class field (ES2022)');
    else if (ts.isClassStaticBlockDeclaration(node)) add(node, 'a class static block (ES2022)');
    else if (ts.isRegularExpressionLiteral(node) && /[dv]/.test(node.text.slice(node.text.lastIndexOf('/')))) add(node, 'the regex flag d or v (ES2022, ES2024)');
    else if (ts.isVariableDeclarationList(node) && node.flags & ts.NodeFlags.Using) add(node, 'a using declaration (ES2026)');
    ts.forEachChild(node, visit);
  })(file);
  const emit = (target) => ts.transpileModule(body, { compilerOptions: { target }, reportDiagnostics: false }).outputText;
  if (!found.length && emit(ts.ScriptTarget.ES2020) !== emit(ts.ScriptTarget.ESNext)) {
    found.push({ offset: 0, line: 0, what: 'syntax that TypeScript rewrites for ES2020' });
  }
  return found.map(({ offset, what }) => ({ offset, what }));
}

// Runs tsc on one config and returns its diagnostics (file is a basename inside the temp folder).
function runTsc(tmp, configName) {
  const [cmd, ...pre] = tscCommand();
  const result = spawnSync(cmd, [...pre, '-p', configName, '--pretty', 'false'],
    { cwd: tmp, encoding: 'utf8', shell: process.platform === 'win32' && cmd === 'tsc' });
  if (result.error) {
    throw new Error(`could not run tsc (${result.error.code ?? result.error.message}); run npm install first`);
  }
  const diags = [];
  for (const line of `${result.stdout}${result.stderr}`.split(/\r?\n/)) {
    const m = /^(.+?)\((\d+),(\d+)\): (?:error|warning) (TS\d+): (.*)$/.exec(line);
    if (m) diags.push({ file: basename(m[1]), line: Number(m[2]), column: Number(m[3]), code: m[4], message: m[5] });
    else if (/^\s/.test(line) && line.trim() && diags.length) diags.at(-1).message += ` ${line.trim()}`; // message chain
    else if (line.trim()) diags.push({ file: null, line: 0, column: 0, code: /TS\d+/.exec(line)?.[0] ?? 'tsc', message: line.trim() });
  }
  if (result.status !== 0 && !diags.length) {
    diags.push({ file: null, line: 0, column: 0, code: 'tsc', message: `tsc exited with ${result.status}` });
  }
  return diags;
}

// Checks every ui file of one plugin folder; returns "path:line  code  message" strings, and adds
// the same kind of line to `warnings` for anything it leaves unchecked.
export function checkDir(dir, { keep = false, warnings = [] } = {}) {
  const kitTypes = [join(dir, 'kit.d.ts'), join(REPO, 'kit.d.ts')].find(existsSync);
  const { files, errors } = uiFiles(dir);
  const ts = typescript();
  for (const htmlPath of files) {
    const html = readFileSync(htmlPath, 'utf8');
    const scripts = [];
    for (const s of inlineScripts(html)) {
      if (!s.module) scripts.push(s);
      else warnings.push(`${rel(htmlPath)}:${s.line}  module  warning: a type="module" script is not checked (check-ui reads classic scripts, which the kit uses)`);
    }
    const hasRuntime = scripts.some((s) => s.runtime);
    if (!hasRuntime) {
      errors.push(`${rel(htmlPath)}:1  check-ui  no <script data-kit="runtime"> here; paste the three data-kit blocks from the kit's ui.html`);
    }
    if (!scripts.length) continue;
    if (!kitTypes) {
      errors.push(`${rel(htmlPath)}:1  kit.d.ts  no kit.d.ts next to it or at the repo root`);
      continue;
    }
    const report = (text) => { if (!errors.includes(text)) errors.push(text); }; // kit.d.ts errors show up in both runs
    if (ts) {
      for (const s of scripts) {
        for (const { offset, what } of newerSyntax(ts, s.body)) {
          report(`${rel(htmlPath)}:${htmlLine(html, s.start + offset)}  ES2020  ${what} is newer than ES2020, the kit's browser baseline`);
        }
      }
    } else {
      warnings.push(`${rel(htmlPath)}  ES2020  warning: syntax not checked (TypeScript is not in node_modules; run npm install)`);
    }
    const tmp = mkdtempSync(join(tmpdir(), 'kit-check-ui-'));
    try {
      copyFileSync(kitTypes, join(tmp, 'kit.d.ts'));
      writeFileSync(join(tmp, 'globals.d.ts'), hasRuntime ? GLOBALS : NO_GLOBALS);
      const byFile = new Map(scripts.map((s, i) => [`script-${i + 1}${s.runtime ? '-runtime' : ''}.js`, s]));
      for (const [file, s] of byFile) writeFileSync(join(tmp, file), s.body);
      const runtime = [...byFile.keys()].filter((file) => byFile.get(file).runtime);
      const diags = [];
      if (runtime.length) {
        // The runtime alone and strict: it must not lean on anything a host script declares.
        writeFileSync(join(tmp, 'jsconfig.json'), jsconfig(true, runtime));
        diags.push(...runTsc(tmp, 'jsconfig.json'));
      }
      if (runtime.length < byFile.size) {
        // All scripts, so host code sees whatever earlier scripts declare; keep only host diagnostics.
        writeFileSync(join(tmp, 'jsconfig.host.json'), jsconfig(false, [...byFile.keys()]));
        diags.push(...runTsc(tmp, 'jsconfig.host.json').filter((d) => !runtime.includes(d.file)));
      }
      for (const d of diags) {
        const script = byFile.get(d.file);
        const where = script ? `${rel(htmlPath)}:${htmlLine(html, script.start + tscOffset(script, d.line, d.column))}`
          : d.file === 'kit.d.ts' ? `${rel(kitTypes)}:${d.line}`
          : d.file ? `${rel(htmlPath)} (generated ${d.file}:${d.line})`
          : rel(htmlPath);
        report(`${where}  ${d.code}  ${d.message}`);
      }
    } finally {
      if (keep) console.error(`check-ui: kept ${tmp}`);
      else rmSync(tmp, { recursive: true, force: true });
    }
  }
  return errors;
}

function main(argv) {
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log('usage: node scripts/check-ui.mjs [--keep] [dir ...]');
    return;
  }
  const dirs = argv.filter((a) => !a.startsWith('-'));
  const list = dirs.length ? dirs : defaultDirs();
  const warnings = [];
  let errors;
  try {
    errors = list.flatMap((dir) => checkDir(dir, { keep: argv.includes('--keep'), warnings }));
  } catch (error) {
    console.error(`check-ui: ${error.message}`);
    process.exitCode = 2;
    return;
  }
  for (const line of [...errors, ...warnings]) console.log(line);
  const n = `${list.length} plugin folder${list.length === 1 ? '' : 's'}`;
  const w = warnings.length ? `; ${warnings.length} warning(s)` : '';
  console.log(errors.length ? `check-ui: ${errors.length} error(s) in ${n}${w}` : `check-ui: no type errors in ${n}${w}`);
  process.exitCode = errors.length ? 1 : 0;
}

// import.meta.main needs Node 24.2+; the path comparison covers 24.0 and 24.1.
if (import.meta.main ?? import.meta.filename === realpathSync(process.argv[1] ?? '.')) main(process.argv.slice(2));
